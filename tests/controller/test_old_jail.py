"""New host, old jail, offline: this checkout's controller, server and
acquisition handlers against a managed run whose worker bundle is built from
a frozen earlier release's jail sources (fixtures/worker-af5f801.tar.gz:
guest/, each shipped handler's jail tree and the test `memo` counterpart as
they were at commit af5f801; never regenerated by the host under test).
The checkout's own builder still decides what enters the jail.

  cargo build --bin agentbox-relay
  python3 -I -B -m unittest discover -s tests -t . -p test_old_jail.py
"""
import os
import shutil
import unittest

from tests.controller.harness import HERE, World, frozen_payload
from tests.controller.test_b2 import request
from tests.controller.test_execution import QUICK, final

FIXTURE = f"{HERE}/fixtures/worker-af5f801.tar.gz"
FROZEN_REVISION = "212394fc27186361914d6a517d00003582cdcbf5333220c25f8972ee47778c38"
# What only the host runs: never in a jail bundle.
HOST_ONLY = ("acquisitions/lib/", "providers/", "src/", "inputs/", "agents/", "images/", "packaging/")


def bundle_files(path):
    return sorted(os.path.relpath(os.path.join(d, n), path) for d, _, names in os.walk(path) for n in names)


class OldJail(unittest.TestCase):
    def setUp(self):
        self.built = frozen_payload(FIXTURE)
        self.world = World(behavior={"engine": True}, built=self.built)
        self.addCleanup(self.world.close)

    def lane(self, text, handlers):
        return self.world.exec(request(text), ["--acquisition-config", self.world.acquisition(handlers)],
                               overrides=QUICK)

    def requests(self):
        return [e["attributes"] for e in self.world.events() if e["event_type"] == "host.handler.request"]

    def test_the_bundle_is_the_frozen_jail_without_host_parts(self):
        self.assertEqual(self.built["revision"], FROZEN_REVISION)
        self.assertEqual(self.world.record()["worker_release"], self.built["release"])
        files = bundle_files(self.built["path"])
        self.assertIn("acquisitions/memo/jail/memo.py", files)
        for handler in ("git", "npm", "pip"):
            self.assertIn(f"acquisitions/{handler}/jail/__init__.py", files)
        for rel in files:
            self.assertFalse(rel.startswith(HOST_ONLY), rel)
            self.assertNotIn("/host/", "/" + rel)
            self.assertFalse(rel.startswith("acquisitions/") and rel.endswith("/manifest.json"), rel)
            self.assertNotEqual(os.path.basename(rel), "agentbox_handler.py", rel)

    def test_a_representative_acquisition_then_stop_and_discard(self):
        """The generic request client (echo) and a jail counterpart through
        its shim (memo), each recorded; then the run's lifecycle."""
        code, out, err = self.lane("agentbox-request echo say '{\"text\":\"old\"}' && memo n1 hello",
                                   {"echo": None, "memo": None})
        self.assertEqual(code, 0, err)
        self.assertIn("outcome=completed", final(out))
        self.assertEqual(out.replace(" ", "").count('"ok":true'), 2, out)
        self.assertIn("memo: ", out)
        self.assertEqual([(r["end"], r["uploaded"]) for r in self.requests()], [("recorded", True), ("recorded", True)])
        code, _, err = self.world.run("stop")
        self.assertEqual(code, 0, err)
        code, _, err = self.world.run("discard")
        self.assertEqual(code, 0, err)
        self.assertEqual(self.world.record()["phase"], "discarded")

    def test_stop_and_discard_need_no_acquisition(self):
        """Without any usable handler tree (an acquisition is refused), the
        old jail's run still stops and is discarded."""
        shutil.rmtree(self.world.handlers)
        code, _, err = self.lane("true", {"echo": None})
        self.assertEqual(code, 1)
        self.assertTrue(err.startswith("agentbox: jail exec refused: "), err)
        code, out, err = self.world.exec(request("true"), overrides=QUICK)
        self.assertEqual(code, 0, err)
        code, _, err = self.world.run("stop")
        self.assertEqual(code, 0, err)
        code, _, err = self.world.run("discard")
        self.assertEqual(code, 0, err)
        self.assertEqual(self.world.record()["phase"], "discarded")


if __name__ == "__main__":
    unittest.main()
